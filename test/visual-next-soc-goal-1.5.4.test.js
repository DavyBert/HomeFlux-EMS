'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const html=fs.readFileSync(path.join(__dirname,'../widgets/status/public/visual.html'),'utf8');
const begin=html.indexOf('function firstUpcomingSocGoal(');
const end=html.indexOf('function renderEnergyDay(){',begin);
assert(begin>=0&&end>begin,'SoC goal-selection helper must be present');
const ctx=vm.createContext({Number,Array});
vm.runInContext(html.slice(begin,end)+'\nthis.choose=firstUpcomingSocGoal;',ctx);
const choose=ctx.choose;
const day={h:17,soc:90};
const morning={h:31,soc:78};
const followingDay={h:41,soc:92};
assert.equal(choose([day,morning,followingDay],15.05).h,17,'at 15:03 the next goal is today at 17:00');
assert.equal(choose([day,morning,followingDay],17).h,31,'at 17:00 the next goal moves to tomorrow 07:00');
assert.equal(choose([morning,day],15).h,17,'selection is chronological even if input order changes');
assert.equal(choose([day,morning,followingDay],31).h,41,'after the morning goal use tomorrow 17:00');
assert.equal(choose([day,morning],32),null,'return no stale target');
assert.equal(choose([{h:16,soc:NaN},day],15).h,17,'discard invalid SOC predictions');
assert(html.includes('const nextGoal=firstUpcomingSocGoal(prediction?.goals,profile.nowH);'));
assert(!html.includes('prediction?.goals?.[1]??prediction?.goals?.[0]'));
assert(html.includes("$('socAtMidnight').textContent=nextGoal?nl(nextGoal.soc,0)+'%':'—'"));
assert(html.includes("$('socProjectionType').textContent=nextGoal?'Tegen '+futureClock(nextGoal.h)"));
console.log('PASS Visual Look: SoC volgend doel follows first upcoming goal and matching projected SoC');
