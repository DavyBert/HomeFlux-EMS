const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname,'..');
const widget = require('../widgets/status/api');
const spec=JSON.parse(fs.readFileSync(path.join(root,'widgets/status/widget.compose.json')));
