'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {emptyDay,calibrateImportedEnergy}=require('../lib/savings');
const day=emptyDay('2026-11-15');
day.unattributedGridKwh=.125;
day.unattributedGridCost=.045;
day.importedEnergyKnown=true;
day.importedEnergyKwh=0;
const calibrated=calibrateImportedEnergy(day);
assert.equal(calibrated.unattributedGridKwh,.125);
assert.equal(calibrated.unattributedGridCost,.045);
day.importedEnergyKwh=.25;
const valid=calibrateImportedEnergy(day);
assert.equal(valid.unattributedGridKwh,.25);
assert.equal(valid.unattributedGridCost,.09);
const root=path.resolve(__dirname,'..');
const settings=fs.readFileSync(path.join(root,'settings/index.html'),'utf8');
const widget=fs.readFileSync(path.join(root,'widgets/savings/public/index.html'),'utf8');
assert(settings.includes('Netimport · bron onbekend'));
assert(settings.includes('data.unattributedGrid?.kwh'));
assert(widget.includes('data.unattributedGrid?.kwh'));
assert(settings.includes("q('panel-savings').classList.contains('active') && Date.now() - lastSavingsRefreshAt >= 60000"));
console.log('Savings metered import calibration and both cost charts PASS');
